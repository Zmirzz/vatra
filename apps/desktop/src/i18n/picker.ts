const roCount = (n: number, one: string, many: string): string => {
  const rest = n % 100;
  return n === 1 ? `1 ${one}` : `${n}${rest === 0 || rest >= 20 ? " de" : ""} ${many}`;
};
const enCount = (n: number, one: string, many: string): string => `${n} ${n === 1 ? one : many}`;

